# Python packages
import numpy as np
import torch
from torchvision import datasets
from torchvision.transforms import ToTensor
import argparse
from tqdm import tqdm
import os
import pickle
import concurrent.futures

# User-defined modules
from classifiers.k_nearest_neighbors import kNearestNeighbors
from data_utils import ACC, get_random_balanced_subset_indices
from argparse_utils import positive_int, float_zero_to_one

def ACC_wrapper(subset_idxs):
    global classifier
    global X_test
    global y_test
    return ACC(classifier, X_test, y_test, subset_idxs)
# Initializer function used to pass classifier, X_test and y_test to child processes
def child_process_init(classifier_instance, test_data, test_labels):
    global classifier
    global X_test
    global y_test
    classifier = classifier_instance
    X_test = test_data
    y_test = test_labels

if __name__ == '__main__':
    # Create an argument parser to set the dataset, subset proportion and number of repetitions
    parser = argparse.ArgumentParser(
        'Script for computing the accuracy of a kNN classifier on multiple random subsets of a target dataset')

    parser.add_argument('dataset', type=str,
                        help='The name of the dataset to be used')

    parser.add_argument('subset_prop', type=float_zero_to_one,
                        help='The proportion of the random subsets generated by the program relative to the full training set')

    parser.add_argument('num_of_rep', type=positive_int,
                        help='The number of random subsets that will be generated')

    args = vars(parser.parse_args())

    dataset_name = args['dataset']
    subset_prop = args['subset_prop']
    num_of_rep = args['num_of_rep']

    # Set a random seed for reproducibility
    random_seed = 42
    np.random.seed(random_seed)
    torch.manual_seed(random_seed)

    # Set the device
    device = 'cuda' if torch.cuda.is_available() else "cpu"
    print(f"Using device: {device}")

    # Get the dataset
    if dataset_name == 'FashionMNIST':
        train_set = datasets.FashionMNIST(root='../datasets/', download=True, transform=ToTensor(), train=True)
        test_set = datasets.FashionMNIST(root='../datasets/', download=True, transform=ToTensor(), train=False)
    elif dataset_name == 'MNIST':
        train_set = datasets.MNIST(root='../datasets/', download=True, transform=ToTensor(), train=True)
        test_set = datasets.MNIST(root='../datasets/', download=True, transform=ToTensor(), train=False)
    else:
        raise argparse.ArgumentTypeError('Unknown dataset name')

    X_train = train_set.data.type(torch.float32)
    y_train = train_set.targets.type(torch.int8).to(device)

    X_test = test_set.data.type(torch.float32)
    y_test = test_set.targets.type(torch.int8).to(device)

    print('Dataset:', dataset_name)
    print('X_train shape:', X_train.shape, X_train.dtype)
    print('y_train shape:', y_train.shape, y_train.dtype)
    print('X_test shape:', X_test.shape, X_test.dtype)
    print('y_test shape:', y_test.shape, y_test.dtype, '\n')

    X_train = torch.reshape(X_train, (X_train.shape[0], -1)).to(device)
    X_test = torch.reshape(X_test, (X_test.shape[0], -1)).to(device)

    # Initialise classifier
    classifier = kNearestNeighbors(X_train, y_train, device)

    # Load distance matrix and sorting indices if they have already been computed in the past
    artifacts_dir_path = '../artifacts/'
    path_1 = artifacts_dir_path + dataset_name + '_dists.pt'
    path_2 = artifacts_dir_path + dataset_name + '_sorting_idxs.npy'
    if os.path.isfile(path_1) and os.path.isfile(path_2):
        print('Distance matrix and sorting indices loaded from file.')
        classifier.dists = torch.load(path_1)
        classifier.sorting_idxs = np.load(path_2)
    else:
        if not os.path.exists(artifacts_dir_path):
            os.makedirs(artifacts_dir_path)
        print('Compute distance matrix and sorting indices.')
        classifier.train(X_test)
        torch.save(classifier.dists, path_1)
        np.save(path_2, classifier.sorting_idxs)

    full_set_acc = ACC(classifier, X_test, y_test, [])
    print('Top-1 acc on full training set: {acc}'.format(acc=full_set_acc))

    results_dir_path = '../results/'
    if not os.path.exists(results_dir_path + dataset_name + '/'):
        os.makedirs(results_dir_path + dataset_name + '/')

    # Save top-1 acc on full training set to file
    if not os.path.isfile(results_dir_path + dataset_name + '/' + 'Full_set_acc_' + dataset_name + '.pkl'):
        print('Saving top-1 acc on full training set to file...')
        with open(results_dir_path + dataset_name + '/' + 'Full_set_acc_' + dataset_name + '.pkl', 'wb') as handle:
            pickle.dump(full_set_acc, handle, protocol=pickle.HIGHEST_PROTOCOL)

    subset_size = (int)(subset_prop * len(train_set))

    filename = dataset_name + '_' + 'random_subset_idxs_subset_prop=' + f'{subset_prop:.4f}' + '.list'
    path_1 = artifacts_dir_path + filename
    if os.path.isfile(path_1):
        print('Loading random subsets list from file...')
        with open(path_1, 'rb') as fp:
            random_subsets = pickle.load(fp)
    else:
        if not os.path.exists(artifacts_dir_path):
            os.makedirs(artifacts_dir_path)
        random_subsets = [get_random_balanced_subset_indices(train_set, subset_size) for i in tqdm(range(num_of_rep))]
        print('Generating and saving random subsets list to file...')
        with open(path_1, 'wb') as fp:
            pickle.dump(random_subsets, fp)

    print('Computing subset ACCs...')
    acc = []
    with concurrent.futures.ProcessPoolExecutor(max_workers=os.cpu_count(), initializer=child_process_init,
                                           initargs=(classifier, X_test, y_test)) as executor:

        for ACC in tqdm(executor.map(ACC_wrapper, random_subsets)):
            acc.append(ACC)

    print('Saving ACCs to file...')
    acc = np.array(acc)
    path_2 = results_dir_path + dataset_name + '/'
    identifier = 'Random_subset_acc_' + dataset_name + '_subset_prop=' + f'{subset_prop:.4f}'

    if not os.path.exists(path_2):
        os.makedirs(path_2)
    np.save(path_2 + identifier, acc)
    print('Done!\n')