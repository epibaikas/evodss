def fitness_func(solution):
    global classifier, X_test, y_test
    fitness = ACC(classifier, X_test, y_test, solution)
    return fitness
def crossover_func(parents, offspring_size, ga_instance):
    offspring = np.zeros(offspring_size, dtype=int)

    # Sort the contents of the parent subsets in ascending order to eliminate duplicates when doing the crossover
    parents = np.sort(parents, axis=1)

    for k in range(offspring_size[0]):
        crossover_point = np.random.randint(low=0, high=parents.shape[1], size=1)[0]

        parent1_idx = k % parents.shape[0]
        parent2_idx = (k+1) % parents.shape[0]

        offspring[k, 0:crossover_point] = parents[parent1_idx, 0:crossover_point]
        offspring[k, crossover_point:] = parents[parent2_idx, crossover_point:]
    return offspring
def mutation_func(offspring, ga_instance):
    # Calculate the number of genes to be mutated based on the specified mutation percent
    num_of_genes_to_mutate = (int)((ga_instance.mutation_percent_genes/100) * offspring.shape[1])
    gene_space = set(ga_instance.gene_space)

    for k in range(offspring.shape[0]):
        # Create a set out of the genes included in the non-mutated offspring
        original_offspring = set(offspring[k])

        # Find the genes which are not included into the non-mutated offspring
        available_genes = list(gene_space - original_offspring)
        # Shuffle the list of available genes so that it is not sorted
        random.shuffle(available_genes)
        # Generate an array of random positions in the offspring which will be mutated
        random_idx = np.random.randint(low=0, high=offspring.shape[1], size=num_of_genes_to_mutate)

        for i in random_idx:
            offspring[k, i] = available_genes.pop()

    return offspring
def on_start(ga_instance):
    print('Genetic Algorithm start', flush=True)
    print("Generation = {generation}, Best top-1 acc/fitness = {fitness}".format(generation=ga_instance.generations_completed,
          fitness=ga_instance.best_solution(pop_fitness=ga_instance.last_generation_fitness)[1]), flush=True)
    global start_time
    start_time = time.time()
def on_generation(ga_instance):
    global start_time
    global get_time_elapsed
    gen = ga_instance.generations_completed
    time_elapsed = time.time() - start_time
    evo_time_elapsed[gen] = time_elapsed
    print("Generation = {generation}, Best top-1 acc/fitness = {fitness}, Time elapsed = {time:3.2} s".format(generation=ga_instance.generations_completed,
    fitness=ga_instance.best_solution(pop_fitness=ga_instance.last_generation_fitness)[1], time=time_elapsed))

# Initializer function used to pass classifier, X_test and y_test to child processes
def child_process_init(classifier_instance, test_data, test_labels):
    global classifier
    global X_test
    global y_test
    classifier = classifier_instance
    X_test = test_data
    y_test = test_labels

# Modification of the GA class to use multiprocessing. The built-in multiprocessing could not be used because there was
# no way to pass the classifier, X_test and y_test variables required by the fitness_func to the child processes.
class MultiprocessGA(pygad.GA):
    def cal_pop_fitness(self):
        global executor
        pop_fitness = ['undefined'] * len(self.population)
        solution_idxs = list(range(0, len(self.population)))

        for idx, fitness in tqdm(zip(solution_idxs, executor.map(fitness_func, self.population))):
            pop_fitness[idx] = fitness

        pop_fitness = np.array(pop_fitness)
        return pop_fitness

if __name__ == '__main__':
    mp.set_start_method('spawn')

    # Create an argument parser to set the dataset, subset proportion and number of iteration
    parser = argparse.ArgumentParser(
        'Script for improving the accuracy of kNN classifier on a subset of the FashionMNIST training set via genetic algorithms')

    parser.add_argument('dataset', type=str,
                        help='The name of the dataset to be used')

    parser.add_argument('subset_prop', type=float_zero_to_one,
                        help='The size of the random subsets generated by the program')

    parser.add_argument('iter', type=positive_int,
                        help='The iteration of the GA instance for the given subset size and dataset')

    args = vars(parser.parse_args())

    subset_prop = args['subset_prop']
    dataset_name = args['dataset']
    iter = args['iter']

    # Adjust the random seed based on the interation number to obtain different results at every repetition of the
    # GA execution
    random_seed = 41 + iter
    np.random.seed(random_seed)
    torch.manual_seed(random_seed)

    # Set the device
    device = 'cuda' if torch.cuda.is_available() else "cpu"
    print(f"Using device: {device}")

    # Get the dataset
    if dataset_name == 'FashionMNIST':
        train_set = datasets.FashionMNIST(root='datasets/', download=True, transform=ToTensor(), train=True)
        test_set = datasets.FashionMNIST(root='datasets/', download=True, transform=ToTensor(), train=False)
    elif dataset_name == 'MNIST':
        train_set = datasets.MNIST(root='datasets/', download=True, transform=ToTensor(), train=True)
        test_set = datasets.MNIST(root='datasets/', download=True, transform=ToTensor(), train=False)

    X_train = train_set.data.type(torch.float32)
    y_train = train_set.targets.type(torch.int8).to(device)

    X_test = test_set.data.type(torch.float32)
    y_test = test_set.targets.type(torch.int8).to(device)

    print('Dataset:', dataset_name)
    print('X_train shape:', X_train.shape, X_train.dtype)
    print('y_train shape:', y_train.shape, y_train.dtype)
    print('X_test shape:', X_test.shape, X_test.dtype)
    print('y_test shape:', y_test.shape, y_test.dtype, '\n')

    X_train = torch.reshape(X_train, (X_train.shape[0], -1)).to(device)
    X_test = torch.reshape(X_test, (X_test.shape[0], -1)).to(device)

    # Initialise classifier
    classifier = kNearestNeighbors(X_train, y_train, device)

    # Load distance matrix sorting indices if they have already been computed in the past
    path_1 = 'artifacts/' + dataset_name + '_dists.pt'
    path_2 = 'artifacts/' + dataset_name + '_sorting_idxs.npy'
    if os.path.isfile(path_1) and os.path.isfile(path_2):
        print('Distance matrix and sorting indices loaded from file.')
        classifier.dists = torch.load(path_1)
        classifier.sorting_idxs = np.load(path_2)
    else:
        if not os.path.exists('artifacts/'):
            os.makedirs('artifacts/')
        print('Compute distance matrix and sorting indices.')
        classifier.train(X_test)
        torch.save(classifier.dists, path_1)
        np.save(path_2, classifier.sorting_idxs)

    subset_size = (int)(subset_prop * len(train_set))

    # Genetic algorithm parameters
    num_generations = 200
    num_parents_mating = 20

    sol_per_pop = 100
    num_genes = subset_size

    init_range_low = 0
    init_range_high = len(train_set) - 1
    gene_space = range(len(train_set))

    parent_selection_type = 'sss'

    crossover_type = 'single_point'

    mutation_type = 'random'
    mutation_percent_genes = 10

    keep_elitism = 1

    ga_instance = MultiprocessGA(num_generations=num_generations,
                           num_parents_mating=num_parents_mating,
                           fitness_func=fitness_func_dummy,
                           sol_per_pop=sol_per_pop,
                           num_genes=num_genes,
                           gene_type=int,
                           init_range_low=init_range_low,
                           init_range_high=init_range_high,
                           gene_space=gene_space,
                           parent_selection_type=parent_selection_type,
                           keep_elitism=keep_elitism,
                           crossover_type=crossover_func,
                           mutation_type=mutation_func,
                           mutation_percent_genes=mutation_percent_genes,
                           allow_duplicate_genes=False,
                           random_seed=random_seed,
                           save_solutions=False,
                           save_best_solutions=True,
                           on_start=on_start,
                           on_generation=on_generation)

    ga_instance.summary()

    start_time = 0
    evo_time_elapsed = np.zeros(num_generations+1)

    executor = concurrent.futures.ProcessPoolExecutor(max_workers=10, initializer=child_process_init, initargs=(classifier, X_test, y_test))
    ga_instance.run()

    solution, solution_fitness, solution_idx = ga_instance.best_solution()
    print("\nParameters of the best solution : {solution}".format(solution=solution))
    print("Fitness value of the best solution = {solution_fitness}".format(solution_fitness=solution_fitness))

    del executor

    print('Saving GA execution results to file...')
    output_folder_path = 'output/' + dataset_name + '/'
    if not os.path.exists(output_folder_path):
        os.makedirs(output_folder_path)

